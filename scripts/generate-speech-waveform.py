#!/usr/bin/env python3
"""Build a visual-only speech spectrum fixture (no runtime recording or audio playback).

Pass --input path/to/speech.wav, or on macOS omit it to synthesize the reference
phrase using the installed Samantha voice. Requires ffmpeg; no Python packages.
Audio intermediates stay under catalog/build/. Only derived normalized bands ship.
"""
import argparse
from array import array
import math
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'catalog/src/shared/kotlin/com/singleoriginapps/animatables/samples/SpeechWaveformSamples.kt'
RATE = 16000
FRAME_MILLIS = 32
BANDS = 24
PHRASE = 'Small details make a big difference. Make a little room for your next idea.'


def band_power(samples, frequency):
    # Hann-windowed Goertzel power, averaged across nearby frequencies below.
    coefficient = 2 * math.cos(2 * math.pi * frequency / RATE)
    previous = previous2 = 0.0
    for sample in samples:
        current = sample + coefficient * previous - previous2
        previous2, previous = previous, current
    return max(0, previous2 ** 2 + previous ** 2 - coefficient * previous * previous2)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path)
    args = parser.parse_args()
    source = args.input
    if source is None:
        source = ROOT / 'catalog/build/generated/audio/speech.aiff'
        source.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['say', '-v', 'Samantha', '-r', '180', '-o', str(source), PHRASE], check=True)
    pcm = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source), '-ac', '1', '-ar', str(RATE), '-f', 's16le', '-'])
    signal = array('h')
    signal.frombytes(pcm)
    if sys.byteorder != 'little':
        signal.byteswap()
    if len(signal) < RATE // 4 or not any(signal):
        raise RuntimeError("Speech input is empty or silent; supply a non-silent WAV with --input.")
    step = RATE * FRAME_MILLIS // 1000
    # Adjacent logarithmic bands share energy, reducing isolated blinking needles.
    centers = [120 * (5000 / 120) ** (i / (BANDS - 1)) for i in range(BANDS)]
    frames = []
    for offset in range(0, len(signal), step):
        window = signal[offset:offset + step]
        samples = [(sample / 32768) * (.5 - .5 * math.cos(2 * math.pi * i / (step - 1))) for i, sample in enumerate(window)]
        values = []
        for center in centers:
            power = sum(band_power(samples, center * ratio) for ratio in (.9, 1, 1.1)) / 3
            amplitude = 4 * math.sqrt(power) / step
            # Fixed dB mapping retains quiet gaps; it never boosts every frame to full height.
            db = 20 * math.log10(max(amplitude, 1e-8))
            values.append(max(0, min(100, round((db + 60) / 48 * 100))))
        frames.append(values)
    frames.extend([[0] * BANDS for _ in range(12)])
    lines = [
        '// Generated by scripts/generate-speech-waveform.py; do not edit the band data.',
        'package com.singleoriginapps.animatables.samples', '',
        '/** A visual-only speech fixture: 32ms windows, 24 log-spaced energy bands, fixed dB gain. */',
        'internal object SpeechWaveformSamples {',
        f'    const val FrameMillis = {FRAME_MILLIS}L',
        '    const val InitialFrame = 8',
        '    private val frames = listOf(',
    ]
    lines.extend('        intArrayOf(' + ','.join(map(str, frame)) + '),' for frame in frames)
    lines.extend(['    )', '', '    fun levels(frame: Int): List<Float> =',
                  '        frames[((frame % frames.size) + frames.size) % frames.size].map { it / 100f }', '}', ''])
    OUTPUT.write_text('\n'.join(lines))
    print(f'Generated {len(frames)} speech frames ({len(frames) * FRAME_MILLIS / 1000:.2f}s), {BANDS} bands')


if __name__ == '__main__':
    main()
