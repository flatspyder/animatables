#!/usr/bin/env python3
"""Generate the small Kotlin vector subset used by the library and its catalogs.

Source: Google's Material Symbols Rounded, 400 weight, unfilled, 24px optical size.
Assets are Apache-2.0 licensed. Re-run explicitly when updating the pinned revision.
"""
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REVISION = '10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7'
GROUPS = {
    'animatables/src/commonMain/kotlin/com/singleoriginapps/animatables/MaterialSymbols.kt': (
        'com.singleoriginapps.animatables', ['check', 'error', 'expand_more']),
    'catalog/src/shared/kotlin/com/singleoriginapps/animatables/samples/MaterialSymbols.kt': (
        'com.singleoriginapps.animatables.samples',
        ['add', 'remove', 'check', 'close', 'menu', 'mic', 'mic_off', 'verified', 'arrow_back']),
}


def generate():
    for target, (package, symbols) in GROUPS.items():
        lines = [
            '// Generated by scripts/generate-material-symbols.py. Do not edit paths by hand.',
            '// Material Symbols by Google, Apache-2.0. See THIRD_PARTY_NOTICES.md.',
            f'// Source revision: {REVISION}',
            f'package {package}', '',
            'import androidx.compose.ui.graphics.Color',
            'import androidx.compose.ui.graphics.SolidColor',
            'import androidx.compose.ui.graphics.vector.ImageVector',
            'import androidx.compose.ui.graphics.vector.addPathNodes',
            'import androidx.compose.ui.unit.dp', '',
            'internal object MaterialSymbols {',
        ]
        for symbol in symbols:
            url = f'https://raw.githubusercontent.com/google/material-design-icons/{REVISION}/symbols/web/{symbol}/materialsymbolsrounded/{symbol}_24px.svg'
            svg = ET.fromstring(urllib.request.urlopen(url, timeout=30).read())
            paths = [element.attrib['d'] for element in svg if element.tag.endswith('path')]
            name = ''.join(word.capitalize() for word in symbol.split('_'))
            # Google uses a negative Y viewBox. Translate the unchanged path data into Compose.
            path_data = ' '.join(paths)
            lines += [f'    const val {name}Path = "{path_data}"',
                      f'    val {name}: ImageVector by lazy {{ symbol("{name}", {name}Path) }}', '']
        lines += ['    private fun symbol(name: String, path: String): ImageVector =',
                  '        ImageVector.Builder(name, 24.dp, 24.dp, 960f, 960f).apply {',
                  '            addGroup(translationY = 960f)',
                  '            addPath(addPathNodes(path), fill = SolidColor(Color.Black))',
                  '            clearGroup()',
                  '        }.build()', '}', '']
        (ROOT / target).write_text('\n'.join(lines))


if __name__ == '__main__':
    generate()
